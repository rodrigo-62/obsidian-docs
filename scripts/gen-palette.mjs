// Generate src/styles/palette.css from an Obsidian app.css (read-only input).
//
// Obsidian defines its colours in two steps: `.theme-light` / `.theme-dark`
// set --color-base-* (and a few overrides), and `body` maps ~240 semantic
// variables onto them (--background-primary: var(--color-base-00), …). The
// mapping is resolved on <body>, so overriding --color-base-* on a child does
// nothing. A per-page theme therefore re-declares the mapping together with
// its own base palette on the page container (see docs/RESEARCH.md).
//
// Usage: node scripts/gen-palette.mjs path/to/app.css   (the output file is committed)
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) {
	console.error('usage: node scripts/gen-palette.mjs path/to/app.css');
	process.exit(1);
}
const css = readFileSync(src, 'utf8');
const rules = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map((m) => ({ sel: m[1].trim(), body: m[2] }));
const decls = (body) =>
	body
		.split(';')
		.map((d) => d.trim())
		.filter((d) => d.startsWith('--'));

const COLOR_REF = /var\(--(color-base|color-accent|background|text-|interactive|color-(red|orange|yellow|green|cyan|blue|purple|pink)|mono-|highlight)/;
const SKIP = /^--(font|anim|size|radius|icon-size|input-height|bases|line-height|header-height|file-|layer|z-|border-width|cursor|scrollbar-radius|toggle-|slider-|checkbox-size|nav-item-size|tab-stacked|vault-profile|dialog|modal-|prompt-|popover-width|ribbon-width|sidebar|status-bar-(font|scroll)|zoom|h[1-6]-(size|weight|line|font|style|variant)|inline-title-(size|weight|line|font|style|variant)|list-(indent|spacing|bullet-size|marker)|table-(header|cell)-(size|weight)|blockquote-(border-thickness|font)|code-(size|radius|white-space)|callout-(padding|radius|border-width|title|content|blend|icon)|embed-(padding|border)|metadata-(padding|gap|label-width|property-radius|input-height|divider)|tag-(size|padding|radius|weight|decoration)|link-(weight|decoration))/;

const body = rules.filter((r) => r.sel === 'body').flatMap((r) => decls(r.body));
const mapped = body.filter((d) => COLOR_REF.test(d) && !SKIP.test(d));
const theme = (name) => rules.filter((r) => r.sel === name).flatMap((r) => decls(r.body));

// Paper palettes: Obsidian's defaults, nudged towards Google Docs' paper look.
const paper = {
	light: ['--color-base-00: #ffffff', '--color-base-05: #fcfcfc', '--color-base-100: #1f1f1f', '--folio-surround: #eef0f2', '--folio-page-shadow: 0 1px 3px rgba(60, 64, 67, 0.18), 0 4px 12px rgba(60, 64, 67, 0.10)'],
	dark: ['--color-base-00: #1f1f1f', '--color-base-05: #232323', '--color-base-100: #e3e3e3', '--folio-surround: #141414', '--folio-page-shadow: 0 1px 3px rgba(0, 0, 0, 0.6), 0 6px 18px rgba(0, 0, 0, 0.45)'],
};

const block = (cls, scheme, themeDecls, extra) =>
	`.view-content.${cls} {\n\tcolor-scheme: ${scheme};\n` +
	[...mapped, ...themeDecls, ...extra].map((d) => `\t${d};`).join('\n') +
	'\n}\n';

const out =
	`/* GENERATED by scripts/gen-palette.mjs from Obsidian's app.css — do not edit by hand.\n` +
	`   Per-page "paper" themes: Obsidian's light/dark palettes plus the body-level colour\n` +
	`   mappings, re-declared on the page container so they resolve against it. */\n\n` +
	block('folio-theme-light', 'light', theme('.theme-light'), paper.light) +
	'\n' +
	block('folio-theme-dark', 'dark', theme('.theme-dark'), paper.dark);

writeFileSync(new URL('../src/styles/palette.css', import.meta.url), out);
console.log(`wrote src/styles/palette.css (${mapped.length} mapped + ${theme('.theme-light').length}/${theme('.theme-dark').length} theme declarations)`);
